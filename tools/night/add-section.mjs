const fmt = (s) => {
  const lines = [
    '    {',
    `      h2: ${JSON.stringify(s.h2).replace(/"/g, "'")},`,
    '      body: [',
    ...s.body.map((b) => `        ${JSON.stringify(b).replace(/"/g, "'")},`),
    '      ],',
    ...(s.note ? [`      note: ${JSON.stringify(s.note).replace(/"/g, "'")},`] : []),
    '    },',
  ];
  return lines.join('\n');
};

let added = 0, renamed = 0;
for (const no of Object.keys(EXTRA).map(Number).sort((a, b) => a - b)) {
  const p = path.join(DIR, `${no}.mjs`);
  let src = fs.readFileSync(p, 'utf8');

  /* 구역 배열의 닫는 자리 — reveal 바로 앞의 "  ],\n\n  reveal:" */
  const marker = '  ],\n\n  reveal:';
  if (!src.includes(marker)) { console.log(`★ ${no}.mjs 구역 끝을 못 찾음`); continue; }
  src = src.replace(marker, `${fmt(EXTRA[no])}\n  ],\n\n  reveal:`);
  added++;

  if (RENAME[no]) {
    const [from, to] = RENAME[no];
    if (!src.includes(`h2: '${from}'`)) console.log(`★ ${no}.mjs H2 '${from}' 못 찾음`);
    else { src = src.replace(`h2: '${from}'`, `h2: '${to}'`); renamed++; }
  }

  if (APPLY) fs.writeFileSync(p, src, 'utf8');
}

console.log(`구역 추가 ${added}개 / H2 질문형 변경 ${renamed}개`);
